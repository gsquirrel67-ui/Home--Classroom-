-- Home- Classroom shared game library
-- Run this in Supabase -> SQL Editor -> New query.
create table if not exists public.games (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 70),
  description text not null default '' check (char_length(description) <= 140),
  html text not null check (char_length(html) <= 200000),
  created_at timestamptz not null default now()
);

alter table public.games enable row level security;

-- Anyone with the public site can read games and submit new games.
create policy "Anyone can read games"
on public.games for select
to anon, authenticated
using (true);

create policy "Anyone can publish games"
on public.games for insert
to anon, authenticated
with check (
  char_length(name) between 1 and 70
  and char_length(description) <= 140
  and char_length(html) <= 200000
);

-- Intentionally no public UPDATE or DELETE policy.
-- Public submissions can still be spammed; add authentication/moderation
-- before sharing widely. Never expose a service_role or secret key in HTML.
